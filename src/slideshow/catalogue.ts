const namespaces: Readonly<Record<string, string>> = {
  'http://schemas.openxmlformats.org/presentationml/2006/main': 'p',
  'http://purl.oclc.org/ooxml/presentationml/main': 'p',
  'http://schemas.microsoft.com/office/powerpoint/2010/main': 'p14',
  'http://schemas.microsoft.com/office/powerpoint/2012/main': 'p15',
  'http://schemas.microsoft.com/office/powerpoint/2015/09/main': 'p159',
}
const byId = new Map(CATALOGUE.map(r => [r.id, r]))
/** Namespace URI or canonical model prefix; unknown namespaces never alias p. */
export function rowForTransition(ns: string, element: string, preset?: string): CatalogueRow | undefined {
  const key = Object.prototype.hasOwnProperty.call(namespaces, ns) ? namespaces[ns] : ns
  const found = byId.get(`transition:${key}:${element}${preset === undefined ? '' : ':' + preset}`)
  return found?.ns === key && found.element === element ? found : undefined
}
/** Exact inventory tuple only. Unknown subtypes remain unknown; no broad fallback. */
export function rowForPreset(cls: string, id: number, subtype?: number): CatalogueRow | undefined {
  if (!Number.isSafeInteger(id) || (subtype !== undefined && !Number.isSafeInteger(subtype))) return undefined
  const found = byId.get(`preset:${cls}:${id}${subtype === undefined ? '' : ':' + subtype}`)
  return found?.preset?.cls === cls && found.preset.id === id && found.preset.subtype === subtype ? found : undefined
}

