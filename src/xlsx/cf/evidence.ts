/**
 * Runtime evidence check keyed by catalog capabilityId (Ruling C1).
 * Derive verified set from manifest/oracle via auditStage1Manifest.
 */
export function hasEvidence(idOrCapability: string, variant?: string): boolean {
  if (testInjectedEvidence) {
    if (variant !== undefined) {
      if (
        testInjectedEvidence.has(`${idOrCapability}:${variant}`) ||
        testInjectedEvidence.has(variant) ||
        testInjectedEvidence.has(idOrCapability)
      ) {
        return true
      }
    } else if (testInjectedEvidence.has(idOrCapability)) {
      return true
    }
    if (testInjectedExact) return false
  }
  if (variant !== undefined) {
    return VERIFIED_CAPABILITIES.has(`${idOrCapability}:${variant}`)
      || VERIFIED_CAPABILITIES.has(variant)
      || VERIFIED_CAPABILITIES.has(idOrCapability)
  }
  return VERIFIED_CAPABILITIES.has(idOrCapability)
}

/**
 * Ruling S3-F as amended (owner, 2026-11-12): what Excel draws for an automatic (`auto="1"`) bar colour, measured from
 * pixels by the oracle and generated by `audit.ts --write --publish-stage3` as `VERIFIED_STAGE3_AUTO_BAR_COLORS` beside
 * the published Stage 3 set. Until that export exists (it does not today) no automatic colour resolves.
 */
// Read through Reflect: the export is optional (absent until Task 23 publishes), so it is not a static import.
const PUBLISHED_AUTO_BAR_COLOURS = Reflect.get(verifiedExports, 'VERIFIED_STAGE3_AUTO_BAR_COLORS') as Readonly<Record<string, string>> | undefined
let testAutoBarColours: Readonly<Record<string, string>> | null = null

/** Test injection of measured automatic colours (capability id to ARGB hex); null clears. Gated by `hasEvidence` too. */
export function injectCfAutoBarColours(colours: Readonly<Record<string, string>> | null): void {
  testAutoBarColours = colours ? { ...colours } : null
}

/**
 * The measured ARGB of an automatic bar colour, only when its capability has evidence AND a measured colour exists
 * for it; an opaque `FFRRGGBB` hex only. Undefined otherwise, so the bar withholds and no colour is ever guessed.
 */
export function autoBarColourEvidence(capability: string): number | undefined {
  if (!hasEvidence(capability)) return undefined
  const hex = (testAutoBarColours ?? PUBLISHED_AUTO_BAR_COLOURS)?.[capability]
  return hex !== undefined && /^FF[0-9A-F]{6}$/i.test(hex) ? parseInt(hex, 16) : undefined
}

/** Ruling S3-B: one layout variant per scope sign (`allPositive`: no axis drawn; `mixedSign`: an axis drawn). */
export type CfBarLayout = Readonly<{ allPositive?: CfBarLayoutVariant; mixedSign?: CfBarLayoutVariant }>
type CfBarLayoutExport = Readonly<Record<string, Readonly<{ origin: string; lengthBasis: string; settledBy: readonly string[] }>>>

/**
 * Ruling S3-B: the layout the oracle selected, generated by `audit.ts --write --publish-stage3` as
 * `VERIFIED_STAGE3_BAR_LAYOUT` beside the published Stage 3 set. Absent today, so no bar has a layout.
 */
// Read through Reflect: the export is optional (absent until Task 23 publishes), so it is not a static import.
const PUBLISHED_BAR_LAYOUT = Reflect.get(verifiedExports, 'VERIFIED_STAGE3_BAR_LAYOUT') as CfBarLayoutExport | undefined
let testBarLayout: CfBarLayoutExport | null = null

/** Test injection of a selected layout (same shape as the export); null clears. Gated by evidence too. */
export function injectCfBarLayout(layout: CfBarLayoutExport | null): void {
  testBarLayout = layout ? JSON.parse(JSON.stringify(layout)) as CfBarLayoutExport : null
}

/**
 * The layout variant of each scope sign, only when the export names a well-formed variant AND every capability that
 * selected it is verified (through `check`, default `hasEvidence`). Undefined when no scope has one: never a default.
 */
export function barLayoutEvidence(check: (capability: string) => boolean = id => hasEvidence(id)): CfBarLayout | undefined {
  const source = testBarLayout ?? PUBLISHED_BAR_LAYOUT
  if (!source) return undefined
  const out: { allPositive?: CfBarLayoutVariant; mixedSign?: CfBarLayoutVariant } = {}
  for (const scope of ['allPositive', 'mixedSign'] as const) {
    const v = source[scope]
    if (!v || (v.origin !== 'span' && v.origin !== 'axis') || (v.lengthBasis !== 'cell' && v.lengthBasis !== 'side')) continue
    if (!Array.isArray(v.settledBy) || v.settledBy.length === 0 || !v.settledBy.every(cap => typeof cap === 'string' && check(cap))) continue
    out[scope] = Object.freeze({ origin: v.origin, lengthBasis: v.lengthBasis })
  }
  return out.allPositive || out.mixedSign ? Object.freeze(out) : undefined
}

export function withCfEvidence<T>(
  capabilityId: string,
  evaluateOrVariant: string | (() => T),
  evaluate?: () => T,
): CfOutcome<T> {
  const [variant, fn] = typeof evaluateOrVariant === 'function'
    ? [undefined, evaluateOrVariant]
    : [evaluateOrVariant, evaluate!]
  return hasEvidence(capabilityId, variant)
    ? { kind: 'ready', value: fn() }
    : { kind: 'unresolved', reason: 'cf-unmeasured-capability' }
}
