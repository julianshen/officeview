/** LO reference direction spelling, not an Office visual-fidelity claim. */
export function presetDirection(cls: string, id: number, subtype: number): string | undefined {
  const resolved = rowForPreset(cls, id, subtype)
  if (!resolved) return undefined
  return resolved.preset?.subtype === subtype ? resolved.uiName.split(': ')[1] : String(subtype)
}
